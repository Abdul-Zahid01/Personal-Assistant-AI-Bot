@pytest.fixture
def alembic_cfg(tmp_path, monkeypatch):
    """Run Alembic in-process against a throwaway SQLite file (no subprocesses: robust on Windows)."""
    monkeypatch.setenv("DATABASE_URL", f"sqlite+aiosqlite:///{tmp_path / 'm.db'}")
    get_settings.cache_clear()
    cfg = Config(str(ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(ROOT / "alembic"))
    yield cfg
    get_settings.cache_clear()


def test_migrations_apply_and_match_the_models(alembic_cfg, tmp_path):
    command.upgrade(alembic_cfg, "head")

    con = sqlite3.connect(tmp_path / "m.db")
    tables = {r[0] for r in con.execute("select name from sqlite_master where type='table'")} - {"alembic_version"}
    assert tables == set(Base.metadata.tables)
    for name, table in Base.metadata.tables.items():
        cols = {r[1] for r in con.execute(f"pragma table_info({name})")}
        assert cols == {c.name for c in table.columns}, name
    con.close()

    try:  # fails if someone changed a model without writing a migration
        command.check(alembic_cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover
        pytest.fail(f"Models and migrations are out of sync: {exc}")

    command.downgrade(alembic_cfg, "base")


def test_every_table_compiles_for_postgres():
    pg = postgresql.dialect()
    for table in Base.metadata.sorted_tables:
        ddl = str(CreateTable(table).compile(dialect=pg))
        assert "TIMESTAMP WITH TIME ZONE" in ddl or not any(c.name.endswith("_at") for c in table.columns), table.name
        for index in table.indexes:
            str(CreateIndex(index).compile(dialect=pg))


def test_models_use_no_dialect_specific_types():
    forbidden = {"UUID", "JSONB", "ARRAY", "ENUM"}
    for table in Base.metadata.tables.values():
        for col in table.columns:
            assert type(col.type).__name__.upper() not in forbidden, (table.name, col.name)


async def test_upgrading_keeps_every_row_and_link(tmp_path):
    """Regression: a SQLite table rebuild with foreign keys ON cascade-deleted all reminders and unlinked blocks."""
    import sqlite3

    from app.db.migrate import alembic_config, prepare_database
    from app.db.session import make_engine

    db = tmp_path / "old.db"
    url = f"sqlite+aiosqlite:///{db}"
    import asyncio
    await asyncio.to_thread(command.upgrade, alembic_config(url), "0002")  # an older app version's database
    con = sqlite3.connect(db)
    con.execute("insert into tasks (id, title, kind, status, priority, estimate_min, actual_min, created_at, updated_at) "
                "values ('t1', 'Report', 'TASK', 'TODO', 'P1', 60, 0, '2026-10-14 04:00:00', '2026-10-14 04:00:00')")
    con.execute("insert into time_blocks (id, task_id, title, kind, start_at, end_at, status, created_at, updated_at) "
                "values ('b1', 't1', 'Report', 'WORK', '2026-10-14 04:00:00', '2026-10-14 05:00:00', 'PLANNED', '2026-10-14 04:00:00', '2026-10-14 04:00:00')")
    con.execute("insert into reminders (id, task_id, block_id, kind, fire_at, text, repeats_left, status, attempts, created_at) "
                "values ('r1', 't1', 'b1', 'BLOCK_START', '2026-10-14 04:00:00', 'go', 0, 'PENDING', 0, '2026-10-14 04:00:00')")
    con.commit()
    con.close()

    engine = make_engine(url)
    assert await prepare_database(engine, url) == "upgraded"
    await engine.dispose()

    con = sqlite3.connect(db)
    assert con.execute("select task_id from time_blocks").fetchall() == [("t1",)]
    assert con.execute("select task_id, block_id from reminders").fetchall() == [("t1", "b1")]
    assert con.execute("pragma foreign_key_check").fetchall() == []
    con.close()


@pytest.mark.parametrize("old_revision", ["0001", "0002", "0003"])
async def test_legacy_database_without_history_is_recognised_and_upgraded(tmp_path, old_revision):
    """Databases made before migrations were tracked (create_all era): same schema as some revision, no history."""
    import asyncio
    import sqlite3

    from app.db.migrate import alembic_config, prepare_database
    from app.db.session import make_engine

    db = tmp_path / "legacy.db"
    url = f"sqlite+aiosqlite:///{db}"
    await asyncio.to_thread(command.upgrade, alembic_config(url), old_revision)
    con = sqlite3.connect(db)
    con.execute("DROP TABLE alembic_version")  # no history, like a database made by the old create_all
    con.commit()
    con.close()

    engine = make_engine(url)
    assert await prepare_database(engine, url) == "upgraded"
    engine = make_engine(url)
    assert await prepare_database(engine, url) == "up to date"
    await engine.dispose()
    con = sqlite3.connect(db)
    assert {"started_at", "routine_id", "remind_before_min"} <= {r[1] for r in con.execute("pragma table_info(tasks)")}
    assert "pinned" in {r[1] for r in con.execute("pragma table_info(time_blocks)")}
    con.close()


async def test_new_database_is_created_and_stamped(tmp_path):
    from app.db.migrate import prepare_database
